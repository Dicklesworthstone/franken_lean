#!/usr/bin/env -S python3 -I -S
"""Bind macro journal identity to the pin's keyed attribute registration.

The existing source-extension contract owns the shared KeyedDecls/scoped-entry
physical layout. This extractor verifies the macro attribute uses that exact
constructor and emits only its structural extension identity.
"""
import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "crates/fln-olean/src/source_extensions/macro_registration_format.rs"


def render():
    records = [line for line in (ROOT / "SUITE.lock").read_text().splitlines()
               if line.startswith("reference ")]
    if len(records) != 1:
        raise ValueError("expected one Reference pin")
    pin = dict(item.split("=", 1) for item in records[0].split()[2:])
    relative = "src/Lean/Elab/Util.lean"
    source = (ROOT / "vendor/lean4-src" / relative).read_text()
    checks = [
        r"^namespace Lean\s*$",
        r"^namespace Elab\s*$",
        r"unsafe def mkMacroAttributeUnsafe \(ref : Name\) : IO \(KeyedDeclsAttribute Macro\) :=\s*\n\s*mkElabAttribute Macro `builtin_macro `macro Name\.anonymous `Lean\.Macro \"macro\" ref",
        r"\[implemented_by mkMacroAttributeUnsafe\]",
        r"opaque mkMacroAttribute \(ref : Name\) : IO \(KeyedDeclsAttribute Macro\)",
        r"builtin_initialize macroAttribute : KeyedDeclsAttribute Macro ← mkMacroAttribute decl_name%",
    ]
    for check in checks:
        if re.search(check, source, re.M) is None:
            raise ValueError(f"macro attribute registration drift: {check}")
    # mkElabAttribute must delegate to the same keyed attribute constructor
    # whose wire layout is extracted by gen_source_extension_contract.py.
    if re.search(r"unsafe def mkElabAttribute\b[\s\S]*?KeyedDeclsAttribute\.init\s*\{[\s\S]*?\} attrDeclName", source) is None:
        raise ValueError("macro attribute no longer uses keyed persistence")
    return "\n".join([
        "//! Generated by scripts/extract/gen_macro_registration_contract.py; do not edit.",
        f"//! Reference: {pin['tag']} @ {pin['commit']}.",
        f"//! {relative}: sha256 {hashlib.sha256(source.encode()).hexdigest()}",
        'pub const MACRO_EXTENSION: &str = "Lean.Elab.macroAttribute";',
        "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if OUTPUT.read_text() != generated:
            raise SystemExit("macro registration contract drift")
    else:
        OUTPUT.write_text(generated)


if __name__ == "__main__":
    main()
