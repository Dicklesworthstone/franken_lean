# Names the pin has REJECTED in binder position during this run. LEAN_KEYWORDS and
# UNWRITABLE_CHARS are my hand-written approximations of the pin's grammar, and a
# keyword missing from them is not a small error: an unescaped keyword is a PARSE
# error, a parse error takes every later declaration in the file with it, and the
# repair loop then blames a dozen innocent rows (measured in wave 13, where `end`
# and `private` cost three demanded rows through exactly that cascade). So every
# name the emitter is about to write BARE is put to the pin first, and anything it
# refuses is escaped instead. Escaping is always sound — «end» IS `end` — so the
# fail-safe direction is to escape, and only the pin's acceptances are trusted.
MEASURED_UNWRITABLE = set()

WRITABLE_PROBE_HEAD = "set_option linter.unusedVariables false\n"


def probe_writable(lean, env, work, names):
    """Return the subset of `names` the pin REFUSES as a bare binder.

    Each candidate is its own command, so a rejection is local: the pin reports it
    and carries on to the next line (verified against the pin — `end` fails while
    the `start` line still runs). A name is treated as writable only when its
    marker actually prints, so a probe that silently produced nothing escapes
    everything rather than waving it all through.
    """
    names = sorted(set(names))
    if not names:
        return set()
    lines = [WRITABLE_PROBE_HEAD]
    for i, n in enumerate(names):
        lines.append(f'#eval (fun {n} => IO.println "FLNOK{i}") 0')
    src = os.path.join(work, "writable.lean")
    with open(src, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    proc = subprocess.run([lean, "-DmaxErrors=100000", src], capture_output=True,
                          text=True, env=env, timeout=1800)
    accepted = set()
    for m in re.finditer(r"FLNOK(\d+)", proc.stdout):
        idx = int(m.group(1))
        if idx < len(names):
            accepted.add(names[idx])
    if not accepted:
        raise SystemExit(
            f"REFUSE: the writability probe accepted none of {len(names)} names — "
            "either the pin refused the whole probe or its marker changed, and a "
            "probe that accepts nothing would escape every field name in the "
            "facade without saying why")
    return set(names) - accepted


def writable_binder(name):
    return writable_component(name)


def needs_rename(name):
    """A binder name that no amount of ESCAPING can make usable.

    `end` and `private` are Lean keywords, and «end» is the same NAME — escaping
    is all they need. Renaming them was a real defect: it emitted
    `structure Lean.Lsp.Range where start : Position; flnp1 : Position`, which has
    different field names from the Reference's and therefore no
    `Lean.Lsp.Range.end` projection at all. Only an inaccessible name (a dagger)
    or one carrying whitespace is genuinely unwritable.
    """
    return (not name) or ("\u271d" in name) or any(ch.isspace() for ch in name)


def binder_text(b, deps):
    """Render one constructor binder so the pin reads it as a binder.

    A name that cannot be written back as source (inaccessible `inst✝`,
    hygienic `inst._@.…._hyg.4`) is dropped where the binder does not need one and
    escaped where it does; a field TYPE that mentions such a name cannot be
    repaired here at all, and the caller refuses structural emission for that
    structure instead."""
    name, ty, kind = b["user"], root_anchor(b["type"], deps), b["kind"]
    # An instance binder's NAME is never referenced, so an unwritable one is
    # DROPPED rather than escaped: `[T]` is the same binder. Testing only for the
    # inaccessible marker missed the hygienic form -- `inst._@.Lean.Data.
    # PersistentHashMap.3696607590._hygCtx._hyg.4` carries neither a dagger nor a
    # writable name, and emitting `[that : BEq α]` is a PARSE error that takes the
    # rest of the file with it (every later declaration then reports as an unknown
    # identifier, which is how one bad binder cost three demanded rows).
    if kind == "inst":
        return f"[{name} : {ty}]" if writable_binder(name) else f"[{ty}]"
    open_, close = {"default": ("(", ")"), "implicit": ("{", "}"),
                    "strict": ("\u2983", "\u2984")}[kind]
    # Defensive: a caller that has not renamed an unwritable binder still emits a
    # NAME here rather than a term the parser will choke on.
    return f"{open_}{safe_ident(name)} : {ty}{close}"


def inductive_block(name, d, iv, ctypes, deps, pks, bs, deps_map,
                    iparams, ctor_bodies, ind_result):
    """Declare a real `inductive`, so the kernel generates its constructors and
    recursor and IOTA-REDUCTION comes back.

    Wave 62 measured what the axiom form costs: 49 rows whose Reference kind is a
    constructor or a recursor were declared as bare axioms, so a match on them
    reduces upstream and is stuck in the facade while every type check passes. A
    structure block already fixes that for single-constructor types; this does it
    for the rest.
    """
    binder = "" if not d["levels"] else ".{" + d["levels"].replace(",", ", ") + "}"
    # THE PARAMETERS COME FROM THE INDUCTIVE'S OWN TYPE. `bs` is the STRUCTURE
    # constructor telescope and the pin reports it only for rows that are
    # structures, so every non-structure inductive arrived here with no binders at
    # all and was written as `inductive Lean.AssocList where` -- no parameters --
    # which is why `Lean.AssocList α β` in its own constructor read "Function
    # expected at" and why all 49 rows written before this were monomorphic enums.
    src = iparams if iparams else bs
    params = []
    for i, b in sorted(src.items()):
        if i >= iv["num_params"]:
            break
        if not iparams:
            b = dict(b, kind=pks.get(i, "default"))
        if b["kind"] != "inst" and needs_rename(b["user"]):
            b = dict(b, user=f"flnp{i}")
        params.append(b)
    if len(params) != iv["num_params"]:
        return None
    own = {name} | set(iv["ctors"])
    rsig = ind_result.get(name)
    head = f"inductive {d['decl_name']}{binder}" + (
        (" " + " ".join(binder_text(b, deps) for b in params)) if params else "")
    if rsig:
        head += " : " + root_anchor(rsig, [x for x in deps if x not in own])
    lines = [head + " where"]
    # the type being declared and its own constructors are in scope UNQUALIFIED
    # inside the block and are not yet at `_root_`, so they are excluded from the
    # anchoring rather than pointed at a name that does not exist yet.
    for c in iv["ctors"]:
        # the constructor's type with the header's parameters ALREADY BOUND; the
        # pin's printing of the full type re-binds them and the kernel rejects the
        # parameter mismatch
        ty = ctor_bodies.get(c) or ctypes.get(c)
        if not ty:
            return None
        short = c.split(".")[-1]
        if not renderable_name(short):
            return None
        cdeps = [x for x in deps_map.get(c, ()) if x not in own]
        lines.append(f"  | {safe_ident(short)} : {root_anchor(ty, cdeps)}")
    return lines


def structural_block(name, d, st, bs, deps, pks):
    """A `class`/`structure` declaration rebuilt from the pin's own constructor
    telescope. This is the ONE thing an axiom facade cannot do: class-hood and
    field projections are structural facts, so an opaque `axiom Lean.MonadEnv`
    makes `[self : Lean.MonadEnv m]` an invalid binder annotation and takes every
    projection down with it (measured: 29 rows plus 20 instance registrations)."""
    keyword = "class" if st["is_class"] else "structure"
    binder = "" if not d["levels"] else ".{" + d["levels"].replace(",", ", ") + "}"
    params, fields = [], []
    for i, b in sorted(bs.items()):
        # The KIND is resolved first. A structure parameter takes its binder kind
        # from the structure's own type, not from the constructor, and the rename
        # below must see the kind it will actually be rendered with: an instance
        # parameter carrying a hygienic name renders as `[ty]` and needs no name,
        # while the same binder rendered explicitly needs a writable one. Renaming
        # before the override left `(inst._@.Lean.Data.PersistentHashMap.…._hyg.4 :
        # BEq α)` in the output, whose `:` is a parse error that takes every later
        # declaration in the file down with it.
        if i < st["num_params"]:
            b = dict(b, kind=pks.get(i, "default"))
        if b["kind"] != "inst" and needs_rename(b["user"]):
            b = dict(b, user=f"flnp{i}")
        (params if i < st["num_params"] else fields).append(b)
    if not fields:
        return None
    # THE ROW'S OWN NAME IS NOT AT `_root_` YET. Inside `structure X where` the
    # name X refers to the declaration being elaborated, and `_root_.X` names
    # nothing at all, so a field whose type mentions X was anchored into
    # "Unknown identifier `_root_.Lean.Language.SnapshotTree`" and the whole block
    # was refused. That is 14 of the 24 structures wave 65 measured falling back
    # to `axiom` and taking their constructors with them. The inductive path was
    # given exactly this exclusion when it was written; the structural path, which
    # is older, never was. Filtering can only affect a row whose own name appears
    # in its own block, and such a row cannot currently be elaborating.
    sdeps = [x for x in deps if x != name]
    head = f"{keyword} {d['decl_name']}{binder}" + (
        (" " + " ".join(binder_text(b, sdeps) for b in params)) if params else "") + " where"
    lines = [head]
    for b in fields:
        # A field name is a SINGLE component: escaping the whole string is right,
        # while splitting it on dots would turn one field into a dotted path.
        fname = safe_ident(b["user"])
        if not fname:
            return None
        lines.append(f"  {fname} : {root_anchor(b['type'], sdeps)}")
    return lines


def probe_generated_ctor_types(lean, env, work, text, decl, deps, owners):
    """Does the constructor Lean GENERATES carry the Reference's type?

    An `inductive` block that elaborates has only proved that it is well formed.
    For an indexed family the pin prints a constructor body without pinning the
    index, so what Lean infers from it here can differ from what the Reference
    holds, and every consumer then type-checks against a constructor that is not
    the Reference's. Each generated constructor is ascribed to the pin's own
    printed type for that constant, and a failure names the OWNING inductive so
    the caller can demote the whole block.

    The check plants a deliberately wrong ascription of its own: if that does not
    fail, the check cannot tell a matching type from a mismatched one and its
    verdicts mean nothing.
    """
    lines = list(text.rstrip("\n").split("\n"))
    lines.append("")
    lines.append("-- GENERATED CONSTRUCTOR TYPE CHECK (not part of the artifact)")
    cmap, n = {}, 0
    for owner in sorted(owners):
        for c in owners[owner]:
            d = decl.get(c) or {}
            ty, dn = d.get("type"), d.get("decl_name")
            if not ty or not dn:
                continue
            lv = d.get("levels") or ""
            b = (".{" + lv.replace(",", ", ") + "}") if lv else ""
            lines.append(f"noncomputable def flnic_{n}{b} : "
                         f"{root_anchor(ty, deps.get(c, ()))} := @{dn}")
            cmap[len(lines)] = (owner, c)
            n += 1
    if not cmap:
        return {}
    first = sorted(owners)[0]
    lines.append(f"noncomputable def flnic_decoy : {TYPE_DECOY_TYPE} := "
                 f"@{decl[first]['decl_name']}")
    cmap[len(lines)] = "@@DECOY@@"
    path = os.path.join(work, "flnic.lean")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    proc = subprocess.run(
        [lean, "-DmaxErrors=4000", "-Dlinter.unusedVariables=false", path],
        capture_output=True, text=True, env=env, timeout=1800)
    out = proc.stdout + proc.stderr
    base = os.path.basename(path)
    bad, decoy_caught = {}, False
    for m in re.finditer(
            rf"{re.escape(base)}:(\d+):\d+: error(?:\(([^)]*)\))?: (.*)", out):
        hit = cmap.get(int(m.group(1)))
        if hit is None:
            continue
        if hit == "@@DECOY@@":
            decoy_caught = True
        else:
            owner, ctor = hit
            bad.setdefault(ctor, (owner,
                                  ((m.group(2) or "-") + ": " + m.group(3))[:200]))
    if not decoy_caught:
        raise SystemExit(
            "REFUSE: the generated-constructor type check did not reject a "
            f"deliberately wrong ascription ({TYPE_DECOY_TYPE}) — it cannot tell "
            "a matching constructor from a mismatched one, so every inductive it "
            "just cleared means nothing")
    # THE SAME PRINTER LADDER EMISSION USES. A first-tier failure here is very
    # often the pin's DEFAULT printing of the constant's own type losing an
    # implicit argument the ascription cannot re-synthesize -- "don't know how to
    # synthesize implicit argument `β`" on an indexed family's constructor is that
    # shape, and so was `Lean.Expr.brecOn` when the projection type check first
    # met it. Demoting a whole inductive on a printing artifact would be a false
    # negative that no later check could recover, so the maximally explicit
    # printing gets the second word. This retry carries its own decoy too.
    retry = [c for c in sorted(bad) if (decl.get(c) or {}).get("typem")]
    if retry:
        rl, rmap = list(text.rstrip("\n").split("\n")), {}
        rl.append("")
        rl.append("-- GENERATED CONSTRUCTOR RETRY at the maximally explicit printing")
        for c in retry:
            d = decl[c]
            lv = d.get("levels") or ""
            b = (".{" + lv.replace(",", ", ") + "}") if lv else ""
            rl.append(f"noncomputable def flnicr_{len(rmap)}{b} : "
                      f"{root_anchor(d['typem'], deps.get(c, ()))} := "
                      f"@{d['decl_name']}")
            rmap[len(rl)] = c
        rl.append(f"noncomputable def flnicr_decoy : {TYPE_DECOY_TYPE} := "
                  f"@{decl[retry[0]]['decl_name']}")
        rmap[len(rl)] = "@@DECOY@@"
        rpath = os.path.join(work, "flnicr.lean")
        with open(rpath, "w", encoding="utf-8") as fh:
            fh.write("\n".join(rl) + "\n")
        rproc = subprocess.run(
            [lean, "-DmaxErrors=4000", "-Dlinter.unusedVariables=false", rpath],
            capture_output=True, text=True, env=env, timeout=1800)
        rout = rproc.stdout + rproc.stderr
        rbase = os.path.basename(rpath)
        still, rdecoy = {}, False
        for m in re.finditer(
                rf"{re.escape(rbase)}:(\d+):\d+: error(?:\(([^)]*)\))?: (.*)",
                rout):
            hit = rmap.get(int(m.group(1)))
            if hit is None:
                continue
            if hit == "@@DECOY@@":
                rdecoy = True
            else:
                still[hit] = ((m.group(2) or "-") + ": " + m.group(3))[:200]
        if not rdecoy:
            raise SystemExit(
                "REFUSE: the maximally-explicit retry of the generated-constructor "
                f"check did not reject a deliberately wrong ascription "
                f"({TYPE_DECOY_TYPE}) — every constructor it just absolved means "
                "nothing")
        for c in retry:
            if c in still:
                bad[c] = (bad[c][0], still[c])
            else:
                del bad[c]
    owners_bad = {}
    for c, (owner, msg) in bad.items():
        owners_bad.setdefault(owner, msg)
    return owners_bad


def refusal_conservation_error(refused, reproduced, unreproduced):
    """Every recorded refusal must come back either reproduced or not reproduced.

    probe_refused_inductives SKIPS a refused row it cannot splice -- no block could
    be built for it, or it never got an `axiom` line to splice over -- and a filter
    that CONTINUES is a sampler: the two verdict lists would then cover fewer rows
    than `inductive_refused` counts, while the manifest presents them as the whole
    story. Nothing else in this run can notice, because both lists are internally
    consistent and every row in them is correct.

    Compared by NAME rather than by count alone, so a row landing in both buckets
    is caught too. Returns an error string, or None when the partition holds.
    """
    refused, reproduced = set(refused), set(reproduced)
    unreproduced = set(unreproduced)
    missing = sorted(refused - reproduced - unreproduced)
    extra = sorted((reproduced | unreproduced) - refused)
    both = sorted(reproduced & unreproduced)
    if missing or extra or both:
        return (f"the {len(refused)} recorded inductive refusals do not partition "
                f"into {len(reproduced)} reproduced and {len(unreproduced)} not "
                f"reproduced. Unaccounted for: {missing[:6]}; verdicts for rows "
                f"that were never refused: {extra[:6]}; rows in both: {both[:6]}. "
                "A refusal with no verdict was silently dropped by the splice, and "
                "the manifest would present the survivors as the whole set")
    return None


def unreproduced_axiom_error(text, line_map, decl, unreproduced):
    """Pin the claim that a not-reproduced refusal actually COSTS something.

    `inductive_refusal_not_reproduced` asserts two things at once: the pin accepts
    the row as an inductive, and the artifact ships it as an axiom anyway. The
    splice measures the first. Nothing measured the second, and it is the half
    that makes the row a finding rather than a note -- if such a row were quietly
    being emitted as an inductive after all, the list would be reporting a loss
    that the artifact does not actually carry.

    Bound to the PUBLISHED bytes: the emitter's own line map has to call the row an
    axiom, and the line it points at in `text` has to be that axiom line, naming
    this row and not a neighbour. Returns an error string, or None.
    """
    lines = text.rstrip("\n").split("\n")
    axiom_line = {hit[1]: ln for ln, hit in line_map.items()
                  if isinstance(hit, tuple) and hit[0] == "axiom"}
    bad = []
    for name in sorted(unreproduced):
        ln = axiom_line.get(name)
        if ln is None:
            bad.append(f"{name}: the emitter did not write it as an axiom")
            continue
        if ln > len(lines):
            bad.append(f"{name}: line {ln} is past the end of the artifact")
            continue
        want = (decl.get(name) or {}).get("decl_name") or name
        line = lines[ln - 1]
        if not line.startswith("axiom ") or not line[6:].startswith(want):
            bad.append(f"{name}: line {ln} is {line[:60]!r}, not its axiom line")
    if bad:
        return ("a row reported as accepted-but-published-as-an-axiom is not "
                f"published as an axiom: {bad[:4]}. That list claims a cost the "
                "artifact would not be paying, and the rows in it would be "
                "findings about nothing")
    return None


def unreproduced_declared_error(unreproduced, inductive_decls):
    """A row cannot be BOTH declared as an inductive and reported as one the
    artifact only publishes as an axiom.

    This is the same claim e35e3521 pins against the emitted BYTES, checked here
    against the emitter's own SET -- `inductive_rows` in the manifest is exactly
    `sorted(inductive_decls)`. The two can disagree, and the way they disagree is
    specific: inductive_block returns None for a row it cannot render, the emit
    loop falls through to the axiom path, and the name stays in inductive_decls
    the whole time. `inductive_rows` would then claim a declaration the artifact
    does not contain, and a not-reproduced row -- one already known to be
    borderline -- is exactly the kind of row that reaches that path.

    Returns an error string, or None.
    """
    both = sorted(set(unreproduced) & set(inductive_decls))
    if both:
        return (f"{len(both)} rows are listed as declared inductives and at the "
                f"same time reported as accepted-but-published-as-an-axiom: "
                f"{both[:4]}. inductive_rows and "
                "inductive_refusal_not_reproduced contradict each other, so one "
                "of the two is describing a facade that was never written")
    return None


def unreproduced_family_error(decl, provided, line_map, unreproduced):
    """The COST of a not-reproduced refusal is the whole family, not just the head.

    Declaring the block would have made the kernel write every constructor under
    it; refusing it leaves each of them as a separate bare axiom, and those rows
    are where the lost iota-reduction actually lives. Two ways that can go wrong,
    and the manifest reports neither:

    A constructor claimed by `provided` while its owner was never declared. That
    is not hypothetical here -- `provided` is populated for every SELECTED
    inductive before the emit loop runs, and a row selected then skipped leaves
    its companions claimed by a block the artifact does not contain. Wave 65 hit
    exactly that shape and it took a pin-side refusal to notice.

    Or a constructor that is neither claimed nor written as an axiom, which means
    the closure dropped it and the family is quietly smaller than the Reference's.

    Returns an error string, or None.
    """
    axiom_rows = {hit[1] for hit in line_map.values()
                  if isinstance(hit, tuple) and hit[0] == "axiom"}
    bad = []
    for owner in sorted(unreproduced):
        family = sorted(n for n in decl if n.startswith(owner + "."))
        if not family:
            bad.append(f"{owner}: no constructor rows at all, yet its block was "
                       "built and accepted")
            continue
        for n in family:
            if n in provided:
                bad.append(f"{n}: claimed as generated by a block that was never "
                           "written")
            elif n not in axiom_rows:
                bad.append(f"{n}: neither claimed nor written as an axiom")
    if bad:
        return ("the family under a row published as an axiom is not itself "
                f"published as axioms: {bad[:4]}. Those constructors are where "
                "the lost iota-reduction lives, so a wrong answer here misstates "
                "the cost the artifact is actually paying")
    return None


def probe_refused_inductives(lean, env, work, text, line_map, decl, deps, blocks):
    """Does a refused inductive still fail against the FINISHED facade?

    A refusal is recorded the moment some attempt's pin run blames the block, and
    the facade at that moment is not the facade that ships: the repair loop is
    still demoting structures, promoting transparents and re-admitting quarantine
    around it. The same non-monotonicity is already recorded for quarantine one
    loop up -- 8 of 16 quarantined rows elaborate cleanly against the finished
    facade -- and nothing was applying it to inductives, so a row could be
    published as "pin rejected the inductive block" when the published artifact
    accepts it.

    Each refused block is spliced in place of the `axiom` line the row actually
    got, so ORDER is tested as it ships rather than by appending at the end, and
    the pin decides. Returns {name: None} when the refusal no longer reproduces
    and {name: reason} when it does.
    """
    lines = text.rstrip("\n").split("\n")
    axiom_line = {}
    for ln, hit in line_map.items():
        if isinstance(hit, tuple) and hit[0] == "axiom":
            axiom_line[hit[1]] = ln
    verdict = {}
    for name in sorted(blocks):
        block, generated = blocks[name]
        ln = axiom_line.get(name)
        if not block or ln is None or ln > len(lines):
            continue
        # DECLARING THE BLOCK MAKES THE KERNEL WRITE ITS CONSTRUCTORS, so the
        # `axiom` lines this facade emitted for those same constants have to come
        # OUT -- that is what `provided` does during real emission. Splicing the
        # block in without removing them made the pin report
        # "`Std.DHashMap.Raw.WF.alter₀` has already been declared", which is a
        # collision this probe created and not a property of the row.
        drop = {axiom_line[g] for g in generated if g in axiom_line}
        variant = []
        for i, line in enumerate(lines, start=1):
            if i in drop:
                continue
            variant.extend(block if i == ln else [line])
        path = os.path.join(work, "flnri.lean")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("\n".join(variant) + "\n")
        proc = subprocess.run(
            [lean, "-DmaxErrors=4000", "-Dlinter.unusedVariables=false", path],
            capture_output=True, text=True, env=env, timeout=1800)
        out = proc.stdout + proc.stderr
        base = os.path.basename(path)
        errs = [m for m in re.finditer(
            rf"{re.escape(base)}:(\d+):\d+: error(?:\(([^)]*)\))?: (.*)", out)]
        if not errs:
            verdict[name] = None
        else:
            first = errs[0]
            verdict[name] = ((first.group(2) or "-") + ": " + first.group(3))[:200]
    return verdict


def structural_refusal(name, st, bs):
    """Why a structure may not be emitted structurally, decided BEFORE the pin is
    asked, so the reason is a fact rather than a diagnostic."""
    if not bs:
        return "no constructor telescope was probed"
    if all(i < st["num_params"] for i in bs):
        return "constructor has parameters only, no fields"
    for i, b in sorted(bs.items()):
        if "\u271d" in b["type"]:
            return "a binder type mentions an inaccessible name"
        # A non-instance binder with an unwritable name is renamed rather than
        # refused — but only when nothing else names it. If a later binder or
        # field type mentions it, the rename would silently change what that type
        # means, so the structure keeps the axiom form instead.
        if b["kind"] != "inst" and needs_rename(b["user"]):
            later = [o["type"] for j, o in sorted(bs.items()) if j > i]
            if any(re.search(r"(?<![\w.])" + re.escape(b["user"]) + r"(?![\w.])", t)
                   for t in later):
                return f"binder {b['user']!r} cannot be written and is referenced"
    return None


DEFAULT_INSTANCE_PRIORITY = 1000


def instance_prio(name, priorities):
    """Render the priority suffix for an `attribute [instance ...]`.

    An instance's PRIORITY decides which of several candidates resolution picks.
    Registering every row at Lean's default silently re-ranks the Reference's
    instances, and nothing downstream would show it: resolution simply succeeds
    with a different instance. The pin's own number is used, and the suffix is
    omitted where it already is the default so the artifact stays readable.
    """
    prio = priorities.get(name)
    if prio is None or prio == DEFAULT_INSTANCE_PRIORITY:
        return ""
    return f" {prio}"


def render(tag, ordered, decl, explicit_for, maxexp_for, quarantine, dropped_attrs,
           structural, structs, binders, deps, pbinders, transparent,
           value_explicit_for, companions, priorities, inductives,
           pin_inductives_ref, types_ref, ind_companions, ctor_companions,
           ind_params_ref, ctor_bodies_ref, ind_result_ref):
    body = [line.replace("{tag}", tag) for line in HEADER]
    line_map = {}
    emitted = []
    # Everything a structural declaration generates for itself: re-declaring a
    # projection the `class` block already produces is a redeclaration error.
    provided = {}
    for i in inductives:
        iv = pin_inductives_ref.get(i) or {}
        for suffix in ind_companions:
            provided[f"{i}.{suffix}"] = i
        for c in iv.get("ctors", ()):
            provided[c] = i
            for suffix in ctor_companions:
                provided[f"{c}.{suffix}" if suffix else c] = i
    for c in structural:
        st = structs[c]
        # The block always generates a PUBLIC `<C>.mk`. Where the Reference's
        # constructor is private (`_private.Lean.Environment.0.…mk`), that private
        # name is NOT what gets generated, and claiming it is a claim the module
        # cannot show — measured as 7 of the 13 withdrawn rows.
        ctor = st["ctor"]
        provided[f"{c}.mk" if ctor.split(".")[0] == "_private" else ctor] = c
        for i, b in sorted(binders.get(c, {}).items()):
            if i >= st["num_params"]:
                provided[f"{c}.{b['user']}"] = c
        for suffix in companions:
            provided[f"{c}.{suffix}"] = c
    for name in ordered:
        if name in quarantine or name in provided:
            continue
        if name in inductives:
            block = inductive_block(name, decl[name],
                                    pin_inductives_ref.get(name) or {},
                                    types_ref, deps.get(name, ()),
                                    pbinders.get(name, {}),
                                    binders.get(name, {}), deps,
                                    ind_params_ref.get(name, {}), ctor_bodies_ref,
                                    ind_result_ref)
            if block is not None:
                d = decl[name]
                body.append(f"-- role={d['role']} bucket={d['bucket']} inductive "
                            f"module={d['module']}")
                for line in block:
                    body.append(line)
                    line_map[len(body)] = ("inductive", name)
                emitted.append(name)
                continue
        if name in structural:
            block = structural_block(name, decl[name], structs[name],
                                     binders.get(name, {}), deps.get(name, ()),
                                     pbinders.get(name, {}))
            d = decl[name]
            body.append(f"-- role={d['role']} bucket={d['bucket']} "
                        f"structural={'class' if structs[name]['is_class'] else 'structure'} "
                        f"module={d['module']}")
            for line in block:
                body.append(line)
                line_map[len(body)] = ("struct", name)
            emitted.append(name)
            continue
        d = decl[name]
        ty = (d["typem"] if name in maxexp_for
              else d["typex"] if name in explicit_for else d["type"])
        if ty is None:
            continue
        ty = root_anchor(ty, deps.get(name, ()))
        if name in transparent:
            binder = "" if not d["levels"] else ".{" + d["levels"].replace(",", ", ") + "}"
            body.append(f"-- role={d['role']} bucket={d['bucket']} transparent "
                        f"module={d['module']}")
            val = (d["valuex"] if name in value_explicit_for and d.get("valuex")
                   else d["value"])
            body.append(f"@[reducible] noncomputable def {d['decl_name']}{binder} : "
                        f"{ty} := {root_anchor(val, deps.get(name, ()))}")
            line_map[len(body)] = ("transparent", name)
            emitted.append(name)
            continue
        body.append(f"-- role={d['role']} bucket={d['bucket']} effect={d['effect']} "
                    f"module={d['module']}" + (" pp=explicit" if name in explicit_for else ""))
        binder = "" if not d["levels"] else ".{" + d["levels"].replace(",", ", ") + "}"
        body.append(f"axiom {d['decl_name']}{binder} : {ty}")
        line_map[len(body)] = ("axiom", name)
        emitted.append(name)
    body.append("")
    attrs = 0
    for name in ordered:
        d = decl[name]
        if name in quarantine or not d["instance"] or name in dropped_attrs:
            continue
        if name in structural:
            continue
        body.append(f"attribute [instance{instance_prio(name, priorities)}] "
                    f"{d['decl_name']}")
        line_map[len(body)] = ("attr", name)
        attrs += 1
    # A parent projection of an `extends` class is an instance in the pin; the
    # structural block generates the projection but not its registration.
    for proj, owner in sorted(provided.items()):
        if proj in decl and decl[proj]["instance"] and proj not in dropped_attrs:
            body.append(f"attribute [instance{instance_prio(proj, priorities)}] "
                        f"{decl[proj]['decl_name']}")
            line_map[len(body)] = ("attr", proj)
            attrs += 1
    for name in sorted(quarantine):
        body.append(f"-- QUARANTINED {name}: {quarantine[name]}")
    return "\n".join(body) + "\n", line_map, emitted, attrs, provided


