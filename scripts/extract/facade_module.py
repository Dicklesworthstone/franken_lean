def unquote(v):
    return v[1:-1] if len(v) >= 2 and v[0] == '"' and v[-1] == '"' else v


def dotted(structural):
    """Decode the census's structural Name encoding into a dotted name.

    `a/s\"Lean\"/s\"Meta\"/s\"Basic\"` -> `Lean.Meta.Basic`. Numeric components
    (`/n3`) are kept as numerals; collapsing them into strings is the f6br defect
    this project has already paid for once.
    """
    parts = []
    for comp in structural.split("/")[1:]:
        if comp.startswith('s\\"') and comp.endswith('\\"'):
            parts.append(comp[3:-2])
        elif comp.startswith('s"') and comp.endswith('"'):
            parts.append(comp[2:-1])
        elif comp.startswith("n"):
            parts.append(comp[1:])
        else:
            return None
    return ".".join(parts) if parts else None


def input_digest(path):
    """Bind a derived artifact to the exact bytes it was derived FROM. Every input
    here is itself generated and is being regenerated by other hands; a summary
    that names its inputs by PATH alone goes stale silently, and the reader cannot
    tell a fresh row from one derived before the input moved."""
    with open(path, "rb") as fh:
        return {"path": os.path.relpath(path, REPO),
                "sha256": hashlib.sha256(fh.read()).hexdigest()}


def pinned_lean():
    with open(os.path.join(REPO, "SUITE.lock"), encoding="utf-8") as fh:
        lock = fh.read()
    tag = None
    for line in lock.splitlines():
        if line.startswith("reference "):
            for field in line.split():
                if field.startswith("tag="):
                    tag = field[4:]
    if not tag:
        raise SystemExit("REFUSE: SUITE.lock has no Reference tag")
    path = os.path.join(
        os.path.expanduser("~"), ".elan", "toolchains",
        f"leanprover--lean4---{tag}", "bin", "lean",
    )
    if not os.path.isfile(path):
        raise SystemExit(f"SKIP: pinned Reference not installed at {path}")
    return path, tag


def load_census():
    """display-name -> census facts, with the shard-completeness refusal.

    Reading one shard of three once manufactured phantom orphans for the
    resistance census; the same trap here would silently declare a closure member
    `Init`-provided (it has no row, so no module) and drop it from the facade.
    """
    facts = {}
    declared = observed = 0
    for shard in ENV_SHARDS:
        if not os.path.isfile(shard):
            raise SystemExit(f"REFUSE: census shard absent: {shard}")
        with open(shard, encoding="utf-8", errors="replace") as fh:
            for line in fh:
                if line.startswith("constant_count\t"):
                    declared = max(declared, int(line.split("\t")[1]))
                if not line.startswith("observed\t"):
                    continue
                observed += 1
                cols = line.rstrip("\n").split("\t")[1:]
                row = {k: unquote(v) for k, v in zip(COLS, cols)}
                facts[row["display"]] = row
    if observed != declared:
        raise SystemExit(
            f"REFUSE: {observed} observed census rows against a declared "
            f"constant_count of {declared} — a partial census would misreport "
            "closure members as Init-provided and drop them from the facade")
    return facts


def demanded_symbols():
    """Toolchain-API symbol rows of the resistance census.

    Tolerates both the pre- and post-totality shapes of fln-facade-resistance/1:
    when a row carries no `partition` field every symbol row is toolchain-api by
    construction (that artifact contained nothing else), and when it does, only
    the toolchain-api rows define the facade surface.
    """
    rows = []
    with open(RESISTANCE, encoding="utf-8") as fh:
        for lineno, line in enumerate(fh, 1):
            try:
                row = json.loads(line)
            except json.JSONDecodeError as exc:
                raise SystemExit(f"REFUSE: {RESISTANCE}:{lineno} is not JSON ({exc})") from exc
            if row.get("kind") != "symbol":
                continue
            if row.get("partition", "toolchain-api") != "toolchain-api":
                continue
            rows.append(row)
    if not rows:
        raise SystemExit(
            "REFUSE: no toolchain-api symbol rows in the resistance census — an "
            "empty facade would compile every probe vacuously")
    return {r["name"]: r for r in rows}


PROBE = r'''import Lean
open Lean in
#eval! show CoreM Unit from do
  let txt <- IO.FS.readFile "@NAMES@"
  let names := ((txt.splitOn "\n").filter (fun s => s != "")).map String.toName
  let env <- getEnv
  for n in names do
    match env.find? n with
    | some info =>
      let fmt <- Meta.MetaM.run' (withOptions
        (fun o => o.setBool `pp.fullNames true) (Meta.ppExpr info.type))
      let fmtx <- Meta.MetaM.run' (withOptions
        (fun o => (o.setBool `pp.fullNames true).setBool `pp.explicit true)
        (Meta.ppExpr info.type))
      -- TIER 3, the maximally explicit rendering. `optParam Lean.Meta.Context { }`
      -- is unreadable to a facade: `{ }` is structure-instance notation, so
      -- re-accepting it needs the structure's field DEFAULTS and the instance
      -- synthesis those defaults perform (Inhabited, EmptyCollection) over types
      -- the facade holds opaquely. With pp.structureInstances and pp.notation off,
      -- the same default prints as a fully applied constructor term with every
      -- instance passed EXPLICITLY -- nothing to synthesize, and every constant in
      -- it is already in the type's used-constant set and therefore in the closure.
      let maxOpts : Options -> Options := fun o0 =>
        let o1 := o0.setBool `pp.fullNames true
        let o2 := o1.setBool `pp.explicit true
        let o3 := o2.setBool `pp.structureInstances false
        let o4 := o3.setBool `pp.notation false
        o4.setBool `pp.fieldNotation false
      let fmtm <- Meta.MetaM.run' (withOptions maxOpts (Meta.ppExpr info.type))
      let inst <- Meta.isInstance n
      match (Meta.instanceExtension.getState env).instanceNames.find? n with
      | some ie => IO.println s!"PRIO\t{n}\t{ie.priority}"
      | none => pure ()
      let redStatus <- getReducibilityStatus n
      let red := match redStatus with
        | ReducibilityStatus.reducible => "reducible"
        | ReducibilityStatus.implicitReducible => "implicitReducible"
        | ReducibilityStatus.semireducible => "semireducible"
        | ReducibilityStatus.irreducible => "irreducible"
      IO.println s!"RED\t{n}\t{red}"
      let sf := match info with
        | ConstantInfo.defnInfo v => match v.safety with
          | DefinitionSafety.safe => "safe"
          | DefinitionSafety.unsafe => "unsafe"
          | DefinitionSafety.partial => "partial"
        | _ => if info.isUnsafe then "unsafe" else "safe"
      IO.println s!"SAFE\t{n}\t{sf}"
      -- NOT the reducing telescope: it unfolds the monad abbreviations, so
      -- CoreM / AttrM / CommandElabM all come back as EST.Out and 81 rows look
      -- like census drift when the census simply recorded the un-reduced head —
      -- which is the head the effect classification is about.
      let rh <- Meta.MetaM.run' (Meta.forallTelescope info.type
        (fun _ body => do
          match body.getAppFn.constName? with
          | some c => pure (toString c)
          | none => pure "-"))
      IO.println s!"RESHEAD\t{n}\t{rh}"
      IO.println s!"EXTERN\t{n}\t{isExtern env n}"
      let knd := match info with
        | ConstantInfo.axiomInfo _ => "axiom"
        | ConstantInfo.defnInfo _ => "def"
        | ConstantInfo.thmInfo _ => "theorem"
        | ConstantInfo.opaqueInfo _ => "opaque"
        | ConstantInfo.quotInfo _ => "quot"
        | ConstantInfo.inductInfo _ => "inductive"
        | ConstantInfo.ctorInfo _ => "ctor"
        | ConstantInfo.recInfo _ => "rec"
      IO.println s!"KIND\t{n}\t{knd}"
      match Compiler.getImplementedBy? env n with
      | some t => IO.println s!"IMPLBY\t{n}\t{t}"
      | none => pure ()
      match env.getModuleIdxFor? n with
      | some idx => IO.println s!"MOD\t{n}\t{env.header.moduleNames[idx.toNat]!}"
      | none => pure ()
      let lvls := ",".intercalate (info.levelParams.map toString)
      let deps := ",".intercalate ((info.type.getUsedConstants.map toString).toList)
      IO.println s!"TYPE\t{n}\t{lvls}\t{inst}\t{fmt}"
      IO.println s!"TYPEX\t{n}\t{fmtx}"
      IO.println s!"TYPEM\t{n}\t{fmtm}"
      IO.println s!"DEPS\t{n}\t{deps}"
      -- A STRUCTURE is the one shape an `axiom` cannot stand in for: class-hood
      -- and field projections are structural facts, not type facts. Report the
      -- constructor telescope so the emitter can rebuild the declaration itself.
      if let ConstantInfo.inductInfo iv := info then
        IO.println s!"IND\t{n}\t{iv.numParams}\t{",".intercalate (iv.ctors.map toString)}"
        -- AN INDUCTIVE'S PARAMETERS, for every inductive and not only for the
        -- ones that are structures. Without these the emitter wrote
        -- `inductive Lean.AssocList where` with no parameters at all, and the
        -- recursive occurrence `Lean.AssocList α β` in its own constructor became
        -- "Function expected at" -- which is why all 49 inductives written so far
        -- are monomorphic enums. The parameter binder kinds come from the
        -- inductive's OWN type; a constructor makes them implicit.
        Meta.MetaM.run' <| Meta.forallBoundedTelescope info.type iv.numParams
            fun ps _ => do
          for i in [0:ps.size] do
            let pd <- ps[i]!.fvarId!.getDecl
            let pty <- withOptions (fun o => o.setBool `pp.fullNames true)
              (Meta.ppExpr pd.type)
            let pk := match pd.binderInfo with
              | BinderInfo.default => "default"
              | BinderInfo.implicit => "implicit"
              | BinderInfo.strictImplicit => "strict"
              | BinderInfo.instImplicit => "inst"
            IO.println s!"IPARAM\t{n}\t{i}\t{pk}\t{pd.userName}\t{pty}"
        -- THE HEADER'S RESULT TYPE, with the parameters bound. An indexed family
        -- carries indices that are NOT parameters -- `Balanced : Impl α β -> Prop`
        -- -- and a header that states only the parameters leaves the indices
        -- unbound, so `Balanced t` in a constructor applies a non-function and the
        -- pin refuses with "Function expected at". This is the signature the pin
        -- itself would print for the row, minus the part the header already binds.
        Meta.MetaM.run' <| Meta.forallBoundedTelescope info.type iv.numParams
            fun _ rest => do
          let rty <- withOptions (fun o =>
              (o.setBool `pp.fullNames true).setBool `pp.fieldNotation false)
            (Meta.ppExpr rest)
          IO.println s!"IRES\t{n}\t{rty}"
        -- and each constructor's type with those parameters ALREADY BOUND: an
        -- `inductive` block states constructor types under the header's
        -- parameters, so the pin's own printing of the full type would re-bind
        -- them and the kernel would reject the parameter mismatch.
        for c in iv.ctors do
          if let some ci := env.find? c then
            Meta.MetaM.run' <| Meta.forallBoundedTelescope ci.type iv.numParams
                fun _ body => do
              -- DOT NOTATION DOES NOT RE-ELABORATE HERE. The pin prints a
              -- constructor body with generalized field notation -- `m.WF` for
              -- `Std.DHashMap.Raw.WF m` -- and reading it back needs the function
              -- to have a parameter whose type is the structure the receiver
              -- belongs to. Against this facade that resolution fails and the pin
              -- refuses the block with "Invalid field notation: Function `WF`
              -- does not have a usable parameter of type `Raw ...`", which is the
              -- whole remaining inductive residue. The notation is a PRINTING
              -- choice, so it is turned off at the source rather than repaired in
              -- the string afterwards.
              let bty <- withOptions (fun o =>
                  (o.setBool `pp.fullNames true).setBool `pp.fieldNotation false)
                (Meta.ppExpr body)
              IO.println s!"CTORB\t{c}\t{bty}"
        if isStructure env n then
          if let some ctor := iv.ctors.head? then
            if let some cinfo := env.find? ctor then
              let cdeps := ",".intercalate ((cinfo.type.getUsedConstants.map toString).toList)
              IO.println s!"STRUCT\t{n}\t{iv.numParams}\t{isClass env n}\t{ctor}"
              let flds := ",".intercalate
                ((getStructureFields env n).map toString).toList
              IO.println s!"FIELDS\t{n}\t{flds}"
              -- The PARAMETER binder kinds come from the structure's OWN type, not
              -- from the constructor: Lean makes constructor parameters implicit,
              -- so emitting `class C {m : X}` from the ctor telescope makes `C m`
              -- "Function expected at C" (measured: 76 rows, 45 of them demanded).
              Meta.MetaM.run' <| Meta.forallTelescopeReducing info.type fun ps _ => do
                for i in [0:ps.size] do
                  let pd <- ps[i]!.fvarId!.getDecl
                  let pk := match pd.binderInfo with
                    | BinderInfo.default => "default"
                    | BinderInfo.implicit => "implicit"
                    | BinderInfo.strictImplicit => "strict"
                    | BinderInfo.instImplicit => "inst"
                  IO.println s!"PBINDER\t{n}\t{i}\t{pk}"
              IO.println s!"DEPSC\t{n}\t{cdeps}"
              Meta.MetaM.run' <| Meta.forallTelescopeReducing cinfo.type fun xs _ => do
                for i in [0:xs.size] do
                  let d <- xs[i]!.fvarId!.getDecl
                  let bty <- withOptions (fun o => o.setBool `pp.fullNames true)
                    (Meta.ppExpr d.type)
                  let bk := match d.binderInfo with
                    | BinderInfo.default => "default"
                    | BinderInfo.implicit => "implicit"
                    | BinderInfo.strictImplicit => "strict"
                    | BinderInfo.instImplicit => "inst"
                  IO.println s!"BINDER\t{n}\t{i}\t{bk}\t{d.userName}\t{bty}"
    | none => IO.println s!"MISSING\t{n}"
'''


VALUE_PROBE = r'''import Lean
open Lean in
#eval! show CoreM Unit from do
  let txt <- IO.FS.readFile "@NAMES@"
  let names := ((txt.splitOn "\n").filter (fun s => s != "")).map String.toName
  let env <- getEnv
  for n in names do
    match env.find? n with
    | some info =>
      match info.value? with
      | some val =>
        let fmt <- Meta.MetaM.run' (withOptions
          (fun o => o.setBool `pp.fullNames true) (Meta.ppExpr val))
        -- The readable rendering of an alias VALUE leaves instance arguments to be
        -- synthesized, and the facade cannot synthesize them: it holds the classes
        -- opaquely. Measured on Lean.PrettyPrinter.Delaborator.OptionsPerPos, whose
        -- transparent form was refused with "failed to synthesize instance of type
        -- class" and which took Lean.PrettyPrinter.delab down with it. The explicit
        -- rendering passes every instance by name, so nothing has to be synthesized.
        let valOpts : Options -> Options := fun o0 =>
          let o1 := o0.setBool `pp.fullNames true
          let o2 := o1.setBool `pp.explicit true
          let o3 := o2.setBool `pp.structureInstances false
          let o4 := o3.setBool `pp.notation false
          o4.setBool `pp.fieldNotation false
        let fmtx <- Meta.MetaM.run' (withOptions valOpts (Meta.ppExpr val))
        let deps := ",".intercalate ((val.getUsedConstants.map toString).toList)
        IO.println s!"VALUE\t{n}\t{fmt}"
        IO.println s!"VALUEX\t{n}\t{fmtx}"
        IO.println s!"VDEPS\t{n}\t{deps}"
      | none => IO.println s!"NOVALUE\t{n}"
    | none => IO.println s!"NOVALUE\t{n}"
'''


def probe_values(lean, env, work, names):
    """Print the VALUE of each named constant.

    Only reducible constants are asked for. A reducible definition is an
    ABBREVIATION in the Reference — `Lean.LMVarId` is `Lean.LevelMVarId`,
    `Lean.Elab.Term.TermElabM` is its reader/state stack — and the pin therefore
    accepts `BEq LevelMVarId` where `BEq LMVarId` is wanted. Declared as an opaque
    axiom, the two become distinct constants with no defeq between them, and every
    row that depends on the unfolding fails. Emitting these transparently is the
    facade being FAITHFUL, not the facade being lenient.
    """
    if not names:
        return {}, {}
    names_path = os.path.join(work, "vnames.txt")
    with open(names_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(sorted(names)) + "\n")
    src = os.path.join(work, "vprobe.lean")
    with open(src, "w", encoding="utf-8") as fh:
        fh.write(VALUE_PROBE.replace("@NAMES@", names_path))
    proc = subprocess.run([lean, src], capture_output=True, text=True, env=env,
                          timeout=1800)
    if proc.returncode != 0:
        raise SystemExit(f"REFUSE: the pinned binary refused the value probe:\n"
                         f"{(proc.stdout + proc.stderr)[:1200]}")
    values, valuesx, vdeps = {}, {}, {}
    current = None
    for line in proc.stdout.splitlines():
        if line.startswith("VALUE\t"):
            _, name, val = line.split("\t", 2)
            values[name] = val
            current = (values, name)
        elif line.startswith("VALUEX\t"):
            _, name, val = line.split("\t", 2)
            valuesx[name] = val
            current = (valuesx, name)
        elif line.startswith("VDEPS\t"):
            _, name, dep_csv = line.split("\t", 2)
            vdeps[name] = [d for d in dep_csv.split(",") if d]
            current = None
        elif line.startswith("NOVALUE\t"):
            current = None
        elif current is not None and line.strip():
            d, name = current
            d[name] = d[name] + " " + line.strip()
    return values, valuesx, vdeps


def probe(lean, env, work, names):
    """Ask the pin for the printed type, universes, instance flag and type-level
    dependencies of each name. Multi-line pp output is rejoined here: the printer
    wraps at its own width, and a probe that pins a width is responsible for an
    option name the pin can move."""
    names_path = os.path.join(work, "names.txt")
    with open(names_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(sorted(names)) + "\n")
    src = os.path.join(work, "probe.lean")
    with open(src, "w", encoding="utf-8") as fh:
        fh.write(PROBE.replace("@NAMES@", names_path))
    proc = subprocess.run([lean, src], capture_output=True, text=True, env=env, timeout=1800)
    if proc.returncode != 0:
        raise SystemExit(f"REFUSE: the pinned binary refused the probe:\n"
                         f"{(proc.stdout + proc.stderr)[:1200]}")
    types, typesx, typesm, levels, insts, deps, missing = {}, {}, {}, {}, {}, {}, []
    reducibility = {}
    safety_status = {}
    module_of = {}
    res_head = {}
    priorities = {}
    extern_of = {}
    impl_by = {}
    kind_of = {}
    inductives = {}
    ind_params = defaultdict(dict)
    ctor_bodies = {}
    ind_result = {}
    structs, binders, pbinders = {}, defaultdict(dict), defaultdict(dict)
    struct_fields = {}
    current = None
    for line in proc.stdout.splitlines():
        if line.startswith("TYPE\t"):
            _, name, lvls, inst, ty = line.split("\t", 4)
            types[name], levels[name], insts[name] = ty, lvls, inst == "true"
            current = (types, name)
        elif line.startswith("TYPEX\t"):
            _, name, ty = line.split("\t", 2)
            typesx[name] = ty
            current = (typesx, name)
        elif line.startswith("TYPEM\t"):
            _, name, ty = line.split("\t", 2)
            typesm[name] = ty
            current = (typesm, name)
        elif line.startswith("RED\t"):
            _, name, status = line.split("\t", 2)
            reducibility[name] = status.strip()
            current = None
        elif line.startswith("SAFE\t"):
            _, name, status = line.split("\t", 2)
            safety_status[name] = status.strip()
            current = None
        elif line.startswith("IND\t"):
            _, name, nparams, ctors = line.split("\t", 3)
            inductives[name] = {"num_params": int(nparams),
                                "ctors": [c for c in ctors.strip().split(",") if c]}
            current = None
        elif line.startswith("KIND\t"):
            _, name, knd = line.split("\t", 2)
            kind_of[name] = knd.strip()
            current = None
        elif line.startswith("IMPLBY\t"):
            _, name, target = line.split("\t", 2)
            impl_by[name] = target.strip()
            current = None
        elif line.startswith("EXTERN\t"):
            _, name, flag = line.split("\t", 2)
            extern_of[name] = flag.strip() == "true"
            current = None
        elif line.startswith("PRIO\t"):
            _, name, prio = line.split("\t", 2)
            priorities[name] = int(prio.strip())
            current = None
        elif line.startswith("RESHEAD\t"):
            _, name, head = line.split("\t", 2)
            res_head[name] = head.strip()
            current = None
        elif line.startswith("MOD\t"):
            _, name, mod = line.split("\t", 2)
            module_of[name] = mod.strip()
            current = None
        elif line.startswith("DEPS\t"):
            _, name, dep_csv = line.split("\t", 2)
            deps[name] = [d for d in dep_csv.split(",") if d]
            current = None
        elif line.startswith("DEPSC\t"):
            _, name, dep_csv = line.split("\t", 2)
            deps[name] = sorted(set(deps.get(name, [])) | {d for d in dep_csv.split(",") if d})
            current = None
        elif line.startswith("FIELDS\t"):
            _, name, flds = line.split("\t", 2)
            struct_fields[name] = [f for f in flds.strip().split(",") if f]
            current = None
        elif line.startswith("STRUCT\t"):
            _, name, nparams, is_class, ctor = line.split("\t", 4)
            structs[name] = {"num_params": int(nparams),
                             "is_class": is_class == "true", "ctor": ctor}
            current = None
        elif line.startswith("PBINDER\t"):
            _, name, idx, kind = line.split("\t", 3)
            pbinders[name][int(idx)] = kind
            current = None
        elif line.startswith("IPARAM\t"):
            _, name, idx, kind, user, bty = line.split("\t", 5)
            ind_params[name][int(idx)] = {"kind": kind, "user": user, "type": bty}
            current = (ind_params[name][int(idx)], "type")
        elif line.startswith("IRES\t"):
            _, name, rty = line.split("\t", 2)
            ind_result[name] = rty
            current = (ind_result, name)
        elif line.startswith("CTORB\t"):
            _, name, bty = line.split("\t", 2)
            ctor_bodies[name] = bty
            current = (ctor_bodies, name)
        elif line.startswith("BINDER\t"):
            _, name, idx, kind, user, bty = line.split("\t", 5)
            binders[name][int(idx)] = {"kind": kind, "user": user, "type": bty}
            current = (binders[name][int(idx)], "type")
        elif line.startswith("MISSING\t"):
            missing.append(line.split("\t", 1)[1])
            current = None
        elif current is not None and line.strip():
            d, name = current
            d[name] = d[name] + " " + line.strip()
    return (types, typesx, typesm, levels, insts, deps, missing,
            structs, {k: v for k, v in binders.items()},
            {k: v for k, v in pbinders.items()}, reducibility, safety_status,
            module_of, struct_fields, res_head, priorities, extern_of, impl_by,
            kind_of, inductives, dict(ind_params), ctor_bodies, ind_result)


IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_'!?]*$")
# A field or binder whose name is a Lean KEYWORD parses as that keyword, and the
# resulting error is a PARSE error, which takes the rest of the file with it: every
# later declaration goes undeclared and reports as "unknown identifier", so the
# repair loop blames a dozen innocent rows and never sees the one bad line.
# Measured on `Lean.NameGenerator.private`, `Lean.Lsp.Range.end`.
LEAN_KEYWORDS = frozenset("""
private protected partial unsafe noncomputable opaque abbrev def theorem axiom
example instance class structure inductive coinductive where extends deriving
namespace section end open export import prelude variable universe mutual
attribute macro macro_rules syntax notation infix infixl infixr prefix postfix
set_option builtin_initialize initialize register_simp_attr
fun let have show suffices calc match with do if then else for in while repeat
try catch finally return break continue unless guard at by from this rec
forall exists sorry admit run_cmd
""".split())


# Lean identifiers are NOT ASCII: `α`, `β`, `σ` and subscripted names are ordinary
# binder names throughout `Lean.*`. Testing writability with an ASCII pattern
# refused `Lean.ToMessageData` and `Lean.Option` over a binder named `α` -- a
# perfectly writable name -- and cost their projections. The test is therefore
# NEGATIVE: a component is writable unless it carries something that cannot appear
# in a Lean identifier.
UNWRITABLE_CHARS = frozenset(
    " \t\n\r.«»✝()[]{}⟨⟩,:;`\"@|=<>#$%^&*+-/\\~")


def writable_component(part):
    # The hand-written rules are the CANDIDATE filter; the pin's own refusals
    # (MEASURED_UNWRITABLE, populated before anything is rendered) are the verdict.
    return (bool(part) and not part[0].isdigit()
            and not (set(part) & UNWRITABLE_CHARS)
            and part not in LEAN_KEYWORDS
            and part not in MEASURED_UNWRITABLE)


def safe_ident(part):
    """One name component, written so the pin reads it as a NAME."""
    if writable_component(part):
        return part
    return "«" + part + "»"
# What a `structure`/`class` block generates alongside its fields is a fact about
# the PIN's elaborator, so it is measured from the pin rather than listed here.
