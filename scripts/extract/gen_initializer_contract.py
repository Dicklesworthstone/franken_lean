#!/usr/bin/env -S python3 -I -S
"""Extract initialization-journal identities from the pinned source, without Lean execution.

The pair layout remains owned by gen_source_extension_contract.py. This contract
adds the two registration identities and verifies that they really use that
ParametricAttribute Name layout, its complete private export, and ordered replay.
"""
import argparse
import importlib.util
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VENDOR = ROOT / "vendor/lean4-src"
OUTPUT = ROOT / "crates/fln-olean/src/initializer_format.rs"


def extract(init, attributes):
    spec = importlib.util.spec_from_file_location(
        "source_contract", ROOT / "scripts/extract/gen_source_extension_contract.py"
    )
    helper = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(helper)
    init = helper.strip_comments(init)
    attributes = helper.strip_comments(attributes)
    if not re.search(r"^namespace Lean\s*$", init, re.M):
        raise ValueError("initializer namespace drift")
    registration = helper.declaration(init, "unsafe def", "registerInitAttrUnsafe")
    for pattern in [
        r"registerParametricAttribute\s*\{",
        r"ref\s*:=\s*ref\s*$",
        r"name\s*:=\s*attrName\s*$",
        r"preserveOrder\s*:=\s*true\s*$",
    ]:
        if not re.search(pattern, registration, re.M):
            raise ValueError("initializer registration or order drift")
    if not re.search(
        r"@\[implemented_by registerInitAttrUnsafe\]\s*private opaque registerInitAttrInner",
        init,
    ):
        raise ValueError("initializer registration implementation drift")
    if not re.search(
        r"def registerInitAttr \(attrName : Name\) \(runAfterImport : Bool\) "
        r"\(ref : Name := by exact decl_name%\) : IO \(ParametricAttribute Name\) :=\s*"
        r"registerInitAttrInner attrName runAfterImport ref",
        init,
    ):
        raise ValueError("initializer extension identity forwarding drift")
    parametric = helper.declaration(attributes, "structure", "ParametricAttribute (α : Type)")
    if not re.search(r"ext\s*:\s*PersistentEnvExtension \(Name × α\) \(Name × α\)", parametric):
        raise ValueError("initializer entry layout drift")
    export = helper.declaration(attributes, "def", "registerParametricAttribute")
    for pattern in [
        r"name\s*:=\s*impl\.ref",
        r"if impl\.preserveOrder then\s*decls\.toArray\.reverse\.filterMap",
        r"\{ exported, server := exported, «private» := all \}",
    ]:
        if not re.search(pattern, export):
            raise ValueError("initializer identity, ordering, or complete private export drift")
    rows = re.findall(
        r"^builtin_initialize (\w+) : ParametricAttribute Name ← registerInitAttr `(\w+) (true|false)\s*$",
        init,
        re.M,
    )
    if len(rows) != 2 or {attr: flag for _, attr, flag in rows} != {
        "init": "true", "builtin_init": "false"
    }:
        raise ValueError(f"initializer registration inventory drift: {rows}")
    names = {attr: f"Lean.{name}" for name, attr, _ in rows}
    return (
        "//! Generated by scripts/extract/gen_initializer_contract.py; do not edit.\n"
        "//! Source: vendor/lean4-src/src/Lean/Compiler/InitAttr.lean and Lean/Attributes.lean.\n"
        "//! Pair fields are extracted separately in source_extension_format.rs.\n"
        f'pub const REGULAR_INIT_EXTENSION: &str = "{names["init"]}";\n'
        f'pub const BUILTIN_INIT_EXTENSION: &str = "{names["builtin_init"]}";\n'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = extract(
        (VENDOR / "src/Lean/Compiler/InitAttr.lean").read_text(encoding="utf-8"),
        (VENDOR / "src/Lean/Attributes.lean").read_text(encoding="utf-8"),
    )
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("initializer contract drift; regenerate and review")
    else:
        OUTPUT.write_text(expected, encoding="utf-8")
    print("initializer contract: two ordered Name-pair journals; checked")


if __name__ == "__main__":
    main()
