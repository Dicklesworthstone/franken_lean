//! Invocation-local Macro.expandMacro? re-entry. Every callback uses the same
//! immutable candidate table and explicit lookup capability as its caller.

use super::*;
use fln_rt::obj::Obj;
use fln_vm::interpreter::{ExecutionLimits, VmRefusal};
use fln_vm::macro_native::{MacroExpansion, MacroExpansionResult};
use std::cell::RefCell;
use std::rc::Rc;

// VM re-entry uses the host stack. Keep its capacity distinct from the Lean
// reader's currRecDepth, which only withIncRecDepth is allowed to change.
// Four re-entries also fit the ordinary Rust test-thread stack in an unoptimized
// build. The cyclic-callback regression must run without a larger stack override.
const MAX_CALLBACK_DEPTH: usize = 4;

pub(super) struct ExpansionWork {
    pub limits: MacroTreeLimits,
    pub usage: MacroTreeUsage,
    pub callback_depth: usize,
    pub conversions: Rc<RefCell<StateBudget>>,
}

impl ExpansionWork {
    pub fn new(limits: MacroTreeLimits) -> Self {
        Self {
            limits,
            usage: MacroTreeUsage::default(),
            callback_depth: 0,
            conversions: Rc::new(RefCell::new(StateBudget::new(
                limits.dispatch.execution.syntax,
            ))),
        }
    }

    pub fn remaining(&self, attempts: usize) -> MacroTreeLimits {
        remaining(self.limits, attempts, &self.usage)
    }

    pub fn generated(
        &mut self,
        syntax: &Syntax,
        source: &SourceText,
    ) -> Result<(), super::super::SyntaxConversionError> {
        let (_, usage) = super::super::syntax::inject_counted(
            syntax,
            source,
            self.limits.dispatch.execution.syntax,
        )?;
        self.usage.generated_nodes = self.usage.generated_nodes.saturating_add(usage.max_nodes);
        self.usage.generated_bytes = self.usage.generated_bytes.saturating_add(usage.max_bytes);
        for (resource, limit, observed) in [
            (
                "tree generated nodes",
                self.limits.generation.max_nodes,
                self.usage.generated_nodes,
            ),
            (
                "tree generated bytes",
                self.limits.generation.max_bytes,
                self.usage.generated_bytes,
            ),
        ] {
            if observed > limit {
                return Err(super::super::SyntaxConversionError::Limit {
                    resource,
                    limit,
                    observed,
                });
            }
        }
        Ok(())
    }
}

fn remaining(
    mut limits: MacroTreeLimits,
    attempts: usize,
    usage: &MacroTreeUsage,
) -> MacroTreeLimits {
    limits.dispatch.max_attempts = limits.dispatch.max_attempts.saturating_sub(attempts as u64);
    limits.max_visits = limits.max_visits.saturating_sub(usage.visits);
    limits.generation.max_nodes = limits
        .generation
        .max_nodes
        .saturating_sub(usage.generated_nodes);
    limits.generation.max_bytes = limits
        .generation
        .max_bytes
        .saturating_sub(usage.generated_bytes);
    limits
}

pub(super) fn add_tree_usage(total: &mut MacroTreeUsage, added: MacroTreeUsage) {
    total.visits = total.visits.saturating_add(added.visits);
    total.generated_nodes = total.generated_nodes.saturating_add(added.generated_nodes);
    total.generated_bytes = total.generated_bytes.saturating_add(added.generated_bytes);
}

pub(super) fn add_vm_usage(total: &mut ExecutionUsage, added: ExecutionUsage) {
    total.steps = total.steps.saturating_add(added.steps);
    total.system_polls = total.system_polls.saturating_add(added.system_polls);
    total.peak_stack_depth = total.peak_stack_depth.max(added.peak_stack_depth);
}

pub(super) struct CallbackProgress {
    pub attempts: Vec<MacroAttempt>,
    pub vm_usage: ExecutionUsage,
    pub tree_usage: MacroTreeUsage,
}

pub(super) struct RegistryExpansion<'a> {
    registry: &'a RegisteredMacros,
    source: &'a SourceText,
    lookup: Option<&'a dyn MacroLookup>,
    limits: MacroTreeLimits,
    callback_depth: usize,
    conversions: Rc<RefCell<StateBudget>>,
    progress: RefCell<CallbackProgress>,
}

impl<'a> RegistryExpansion<'a> {
    pub fn new(
        registry: &'a RegisteredMacros,
        source: &'a SourceText,
        lookup: Option<&'a dyn MacroLookup>,
        limits: MacroTreeLimits,
        callback_depth: usize,
        conversions: Rc<RefCell<StateBudget>>,
    ) -> Self {
        Self {
            registry,
            source,
            lookup,
            limits,
            callback_depth,
            conversions,
            progress: RefCell::new(CallbackProgress {
                attempts: Vec::new(),
                vm_usage: ExecutionUsage {
                    steps: 0,
                    system_polls: 0,
                    peak_stack_depth: 0,
                },
                tree_usage: MacroTreeUsage::default(),
            }),
        }
    }

    pub fn into_progress(self) -> CallbackProgress {
        self.progress.into_inner()
    }

    fn expand(
        &self,
        input: &Obj,
        context: &Obj,
        state: &Obj,
        vm_limits: ExecutionLimits,
        cancellation: Option<&dyn CancellationProbe>,
    ) -> MacroExpansionResult {
        let mut usage = ExecutionUsage {
            steps: 0,
            system_polls: 0,
            peak_stack_depth: 0,
        };
        let outcome = (|| {
            if cancellation.is_some_and(CancellationProbe::is_cancelled) {
                return Outcome::Inconclusive(Inconclusive::cancelled("macro expansion callback"));
            }
            if self.callback_depth >= MAX_CALLBACK_DEPTH {
                return stopped(
                    "macro callback host depth",
                    MAX_CALLBACK_DEPTH as u64,
                    self.callback_depth.saturating_add(1) as u64,
                );
            }
            // Do not retain a RefCell borrow across user code or another callback.
            let mut limits = {
                let progress = self.progress.borrow();
                remaining(self.limits, progress.attempts.len(), &progress.tree_usage)
            };
            limits.dispatch.execution.vm = vm_limits;
            if limits.max_visits == 0 {
                return stopped("macro tree visits", 0, 1);
            }
            let projected = {
                let mut conversions = self.conversions.borrow_mut();
                super::super::project_callback(input, context, state, self.source, &mut conversions)
            };
            let (input, context, reference, state) = match projected {
                Ok(value) => value,
                Err(error) => return callback_conversion(error),
            };
            let mut work = ExpansionWork {
                limits,
                usage: MacroTreeUsage {
                    visits: 1,
                    ..MacroTreeUsage::default()
                },
                callback_depth: self.callback_depth + 1,
                conversions: self.conversions.clone(),
            };
            let mut report = MacroDispatch::empty();
            let result = self.registry.expand(
                &input,
                ExpansionContext {
                    source: self.source,
                    context: &context,
                    reference: Some(&reference),
                    lookup: self.lookup,
                    cancellation,
                },
                state,
                &mut report,
                &mut work,
            );
            usage = report.completed_vm_usage;
            {
                let mut progress = self.progress.borrow_mut();
                add_vm_usage(&mut progress.vm_usage, usage);
                add_tree_usage(&mut progress.tree_usage, work.usage);
                if progress
                    .attempts
                    .try_reserve(report.attempts.len())
                    .is_err()
                {
                    return Outcome::Inconclusive(Inconclusive::dependency_unavailable(
                        "host allocation for nested macro attempts",
                    ));
                }
                progress.attempts.extend(report.attempts);
            }
            match result {
                Outcome::Complete(Ok(result)) => {
                    let injected = {
                        let mut conversions = self.conversions.borrow_mut();
                        super::super::inject_callback_result(result, self.source, &mut conversions)
                    };
                    match injected {
                        Ok(value) => Outcome::Complete(Ok(value)),
                        Err(error) => callback_conversion(error),
                    }
                }
                Outcome::Complete(Err(MacroExecutionError::Runtime(refusal))) => {
                    Outcome::Complete(Err(refusal))
                }
                Outcome::Complete(Err(error)) => {
                    Outcome::Complete(Err(VmRefusal::MacroExpansionInvalid {
                        detail: error.to_string(),
                    }))
                }
                Outcome::Inconclusive(reason) => Outcome::Inconclusive(reason),
                Outcome::InternalFault(fault) => Outcome::InternalFault(fault),
            }
        })();
        MacroExpansionResult { outcome, usage }
    }
}

fn callback_conversion(
    error: super::super::SyntaxConversionError,
) -> Outcome<Result<Obj, VmRefusal>> {
    let error = match error {
        super::super::SyntaxConversionError::Limit {
            resource,
            limit,
            observed,
        } => super::super::SyntaxConversionError::Limit {
            resource: match resource {
                "state nodes" => "macro callback conversion nodes",
                "state bytes" => "macro callback conversion bytes",
                other => other,
            },
            limit,
            observed,
        },
        other => other,
    };
    super::super::conversion_outcome(error).map_complete(|result| {
        result
            .map(|_| unreachable!("failed conversion has no macro result"))
            .map_err(|error| VmRefusal::MacroExpansionInvalid {
                detail: error.to_string(),
            })
    })
}

impl MacroExpansion for RegistryExpansion<'_> {
    fn expand_macro(
        &self,
        syntax: &Obj,
        context: &Obj,
        state: &Obj,
        limits: ExecutionLimits,
        cancellation: Option<&dyn CancellationProbe>,
    ) -> MacroExpansionResult {
        self.expand(syntax, context, state, limits, cancellation)
    }
}
